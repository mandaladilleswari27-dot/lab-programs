 class Concate {
    public static void main(String[] args) {
        String str1 = "Hello";
        String str2 = "Java";
        String str3 = "World";

        System.out.println(str1.concat(str2));
        System.out.println(str2.concat(str3));
        System.out.println(str1.concat(str3));
    }
}


