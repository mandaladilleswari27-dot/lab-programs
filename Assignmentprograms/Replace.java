class Replace {

    public static void main(String[] args) {
        String str1 = "Hello";
        String str2 = "Java";
        String str3 = "World";

        System.out.println(str1.replace('l', 'x'));
        System.out.println(str2.replace('a', 'o'));
        System.out.println(str3.replace('o', 'a'));
    }
}

