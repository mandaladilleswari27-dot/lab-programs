class Uppercase {
    
    public static void main(String[] args) {
        String str1 = "hello";
        String str2 = "java";
        String str3 = "world";

        System.out.println(str1.toUpperCase());
        System.out.println(str2.toUpperCase());
        System.out.println(str3.toUpperCase());
    }
}


